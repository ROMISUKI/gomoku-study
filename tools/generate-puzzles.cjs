  for(const t of [0,1]) puzzles.push({id:s.id+'-'+t,template:s.id,title:s.title+(t?' · 转向练习':''),group:s.group,c:s.c,goal:s.goal,depth:s.depth||0,rule:'freestyle',board:G.transformBoard(b,t),hint:t?rotate(s.hint):s.hint,why:t?rotate(s.why):s.why,orientation:t,solutions:solutions.map(v=>({p:G.transformPoint(v.p,t),proof:transformProof(v.proof,t),line:v.line.map(([p,c])=>[G.transformPoint(p,t),c])}))});
