function validAt(b,p,s){
 if(b[p])return null;
 const c=s.c,z=b.slice();z[p]=c;
 if(s.goal==='win')return G.winsAt(z,p,c)?{move:p,win:true}:null;
 if(s.goal==='block')return G.winningMoves(b,3-c).length>0&&!G.winningMoves(z,3-c).length?{move:p,block:true}:null;
 if(G.winningMoves(z,3-c).length)return null;
 if(s.goal==='openfour')return G.fours(z,p,c).some(f=>f.ends.length>=2)?{move:p,ends:G.winningMoves(z,c)}:null;
 if(s.goal==='double')return G.winningMoves(z,c).length>=2?{move:p,ends:G.winningMoves(z,c)}:null;
 return G.proveVCF(b,c,s.depth,p);
}
function transformProof(proof,t){
 const o={...proof,move:G.transformPoint(proof.move,t)};
 if(proof.ends)o.ends=proof.ends.map(p=>G.transformPoint(p,t));
 if(proof.next){o.defense=G.transformPoint(proof.defense,t);o.next=transformProof(proof.next,t);}
 return o;
}
